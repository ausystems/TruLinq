/* Embeds server/db/migrations/*.sql into server/db/migrations/index.ts so the serverless bundle needs no file reads. */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const dir = fileURLToPath(new URL('../server/db/migrations/', import.meta.url));
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f.replace(/\.sql$/, ''))}, sql: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))} }`);
writeFileSync(join(dir, 'index.ts'), `/* Generated by scripts/bundle-migrations.mjs from the .sql files in this folder. Do not edit by hand. */\nexport interface Migration { name: string; sql: string }\nexport const MIGRATIONS: Migration[] = [\n${entries.join(',\n')}\n];\n`);
console.log(`bundled ${files.length} migrations`);
